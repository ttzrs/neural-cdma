MACROS = {}

def tex(s):
    return str(s).replace('_', r'\_').replace('%', r'\%').replace('&', r'\&')

def num(x, digits=3):
    if x is None:
        return '--'
    if isinstance(x, int):
        return str(x)
    return f'{x:.{digits}f}'

def macro(name, value, source, digits=3):
    assert name.isalpha() and name not in MACROS
    MACROS[name] = {'value': value, 'formatted': num(value, digits), 'source': source}

def table(name, caption, headers, rows, note='', widths=None):
    OUT.mkdir(parents=True, exist_ok=True)
    # Tabulars are shrunk only if needed; their captions remain full size.
    body = ['% Generated by make_tables.py; do not edit.', r'\begin{table}[!htbp]',
            r'\centering\footnotesize\setlength{\tabcolsep}{3.3pt}',
            r'\caption{' + caption + r'}\label{tab:' + name + '}',
            r'\begin{adjustbox}{max width=\linewidth}',
            r'\begin{tabular}{' + (widths or 'l' + 'r' * (len(headers)-1)) + '}',
            r'\toprule', ' & '.join(headers) + r' \\', r'\midrule']
    body += [' & '.join(map(str, row)) + r' \\' for row in rows]
    body += [r'\bottomrule', r'\end{tabular}', r'\end{adjustbox}']
    if note:
        body += [r'\par\smallskip{\scriptsize ' + note + '}']
    body += [r'\end{table}', '']
    (OUT / (name + '.tex')).write_text('\n'.join(body))

def capacity_cells():
    """Fit set: repairs replace matching original (width, vocabulary) cells."""
    original = DATA['capacity_law']['cells']
    fixed = DATA['capacity_fix']
    merged = {(p['d'], p['V']): p for p in original}
    merged.update({(p['d'], p['V']): p for p in fixed})
    return list(merged.values())

def empirical_fit_estimates():
    cells = capacity_cells()
    xs = [p['d'] / p['bits'] for p in cells]
    fit = sum(x*p['k_cap'] for x,p in zip(xs,cells)) / sum(x*x for x in xs)
    # Explicitly reproduce a conservative hundredth-scale reference, not a new fit.
    return fit, math.floor(100 * fit) / 100

def accuracy_table(name, caption, blocks, capacity_key='k_cap', note=''):
    ks = sorted({int(k) for _,p in blocks for k in p.get('accs',p.get('trained',{}))})
    rows=[]
    for label,p in blocks:
        a=p.get('accs',p.get('trained',{}))
        rows.append([tex(label)] + [num(a.get(str(k))) for k in ks] +
                    [str(p[capacity_key]) if capacity_key in p else '--'])
    table(name,caption,['Condition'] + [f'${k}$' for k in ks] + [r'$K_{\rm cap}$'],rows,note)

def split_results(payload, kind):
    """Validate the producer contract, accepting a root held-out capacity field."""
    result = {}
    for split in ['train', 'heldout']:
        block = payload[split]
        if not isinstance(block, dict):
            raise ValueError(f'{kind}/{split}: expected an object')
        block = dict(block)
        if kind == 'language':
            curve = block['trained']
            key = 'k_cap_rel80_heldout' if split == 'heldout' else 'k_cap_rel80'
            cap = block.get(key, payload.get(key, block.get('k_cap_rel80')))
            if cap is None:
                raise ValueError(f'{kind}/{split}: missing capacity')
            block['k_cap_rel80'] = cap
            if str(cap) not in curve:
                raise ValueError(f'{kind}/{split}: capacity is not an evaluated K')
        else:
            for key in ['by_K', 'retention_vs_K1', 'prior_only', 'surprise_terciles']:
                if key not in block:
                    raise ValueError(f'{kind}/{split}: missing {key}')
            if set(block['by_K']) != set(block['retention_vs_K1']):
                raise ValueError(f'{kind}/{split}: recovery/retention grids differ')
        result[split] = block
    return result


def language_blocks(ll, ff, payload=None, selective_payload=None):
    blocks = [('No adaptation / original train', {'trained': ll['untrained']}),
              ('LoRA / original train', ll), ('Full FT / original train', ff)]
    if payload is not None:
        split = split_results(payload, 'language')
        blocks += [('Full FT / new train', split['train']),
                   ('Full FT / held-out', split['heldout'])]
    if selective_payload is not None:
        for label,block in split_results(selective_payload,'surprise').items():
            blocks.append(('LoRA selective / '+('new train' if label=='train' else 'held-out'),
                           {'trained':{k:v['acc_all'] for k,v in block['by_K'].items()},
                            'k_cap_rel80':block['k_cap_rel80']}))
    return blocks


def surprise_blocks(original, payload=None):
    blocks = [('Original train', original)]
    if payload is not None:
        split = split_results(payload, 'surprise')
        blocks += [('New train', split['train']), ('Held-out', split['heldout'])]
    return blocks


